function formatLessonText(text) {
    if (!text) return "";

    const lines = escapeHTML(text).split("\n");
    const sections = [];
    let current = { heading: "", content: [] };

    function saveSection() {
        if (current.heading || current.content.length) {
            sections.push(current);
        }
    }

    lines.forEach(line => {
        line = line.trim();
        if (!line || /^[-*_]{3,}\s*$/.test(line)) return;

        if (/^#{1,6}\s/.test(line)) {
            saveSection();
            current = {
                heading: line.replace(/^#{1,6}\s*/, "").replace(/^\d+[\.\)]\s*/, ""),
                content: []
            };
            return;
        }

        line = line.replace(/^\d+[\.\)]\s*/, "");
        line = line.replace(/^[-*•]\s+/, "");
        line = line.replace(/\*\*(.*?)\*\*/g, "<strong>$1</strong>");
        line = line.replace(/\*(.*?)\*/g, "<em>$1</em>");
        line = line.replace(/`([^`]+)`/g, "<code>$1</code>");

        current.content.push(line);
    });

    saveSection();

    return sections.map(section => {
        const heading = section.heading
            ? `<h3 style="color:#2475C5;margin:0 0 14px;font-size:19px;">${section.heading}</h3>`
            : "";

        const content = section.content.map(line =>
            `<p style="line-height:1.8;margin:10px 0;color:#35445A;">${line}</p>`
        ).join("");

        return `
            <section style="background:#fff;border:1px solid #E2EAF3;
            border-radius:14px;padding:20px;margin:0 0 18px;
            box-shadow:0 2px 8px rgba(30,60,90,0.04);">
                ${heading}${content}
            </section>`;
    }).join("");
}


