async function generateLesson(event) {
    event.preventDefault();

    const topicInput = getElement("topic");
    const lessonElement = getElement("lesson");
    const lessonSection = getElement("lessonSection");
    const topicForm = getElement("topicForm");

    const topic = topicInput.value.trim();

    if (!topic) {
        alert(getText("enterTopic"));
        return;
    }

    currentTopic = topic;
    currentLesson = "";

    const submitButton = topicForm.querySelector('button[type="submit"]');

    if (submitButton) {
        submitButton.disabled = true;
        submitButton.textContent = getText("preparing");
    }

    lessonSection.classList.remove("hidden");
    lessonElement.textContent = getText("preparingLesson");

    try {
        const result = await sendRequest("/api/learn", {
            question: topic,
            lessonLanguage: getSelectedLanguage(
                "lessonLanguage",
                getLanguageLocale(selectedInterfaceLanguage)
            )
        });

        if (!result.answer) {
            throw new Error(getText("lessonError"));
        }

        currentLesson = result.answer;
        lessonElement.innerHTML = formatLessonText(currentLesson);

        saveCompletedLesson(topic);

        getElement("readAloudControls")?.classList.remove("hidden");
        getElement("quizArea")?.classList.remove("hidden");

        if (getElement("quiz")) getElement("quiz").innerHTML = "";
        showMessage(getElement("feedback"), "");

        lessonSection.scrollIntoView({
            behavior: "smooth",
            block: "start"
        });

    } catch (error) {
        lessonElement.textContent =
            getText("lessonError") + " " + error.message;
        console.error("Lesson error:", error);

    } finally {
        if (submitButton) {
            submitButton.disabled = false;
            submitButton.textContent = getText("generate");
        }
    }
}


