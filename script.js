function saveCompletedLesson(topic) {
    if (!learnerProgress.topics.includes(topic)) {
        learnerProgress.topics.push(topic);
    }

    learnerProgress.lessons++;
    saveData("klarivoProgress", learnerProgress);
    updateProgress();
}

function saveQuizScore() {
    const percentage = quizQuestions.length
        ? Math.round(score / quizQuestions.length * 100)
        : 0;

    learnerProgress.scores.push(percentage);
    saveData("klarivoProgress", learnerProgress);
    updateProgress();
}


