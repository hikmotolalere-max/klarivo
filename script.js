async function askKlarivo(event) {
    event.preventDefault();

    const questionInput = getElement("askQuestion");
    const chat = getElement("askChat");
    const askButton = getElement("askButton");

    const question = questionInput.value.trim();
    if (!question) return;

    const userMessage = document.createElement("p");
    userMessage.textContent = getText("yourQuestion") + " " + question;
    userMessage.className = "user-message";
    chat.appendChild(userMessage);

    questionInput.value = "";
    askButton.disabled = true;
    askButton.textContent = getText("thinking");

    const thinking = document.createElement("p");
    thinking.textContent = getText("thinking");
    thinking.className = "assistant-message";
    chat.appendChild(thinking);

    try {
        const result = await sendRequest("/api/ask", {
            lesson: currentLesson,
            question,
            responseLanguage: getSelectedLanguage(
                "responseLanguage",
                getLanguageLocale(selectedInterfaceLanguage)
            )
        });

        thinking.textContent =
            getText("klarivo") + " " + (result.answer || getText("askError"));

    } catch (error) {
        thinking.textContent =
            getText("klarivo") + " " + getText("askError") + " " + error.message;
        console.error("Ask Klarivo error:", error);

    } finally {
        askButton.disabled = false;
        askButton.textContent = getText("askButton");
    }

    chat.scrollTop = chat.scrollHeight;
}


