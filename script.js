function getSpeechLanguage() {
    return getSelectedLanguage(
        "lessonLanguage",
        getLanguageLocale(selectedInterfaceLanguage)
    );
}

function populateReadingVoices() {
    const select = getElement("readingVoice");
    if (!select || !window.speechSynthesis) return;

    const voices = window.speechSynthesis.getVoices();
    select.innerHTML = "";

    const defaultOption = document.createElement("option");
    defaultOption.value = "";
    defaultOption.textContent = getText("defaultVoice");
    select.appendChild(defaultOption);

    voices.forEach((voice, index) => {
        const option = document.createElement("option");
        option.value = String(index);
        option.textContent = `${voice.name} (${voice.lang})`;
        select.appendChild(option);
    });
}

function updateReadAloudButtons(isActive, isPaused = false) {
    const listenButton = getElement("readAloudButton");
    const pauseButton = getElement("pauseReadingButton");
    const stopButton = getElement("stopReadingButton");

    if (listenButton) listenButton.disabled = isActive;

    if (pauseButton) {
        pauseButton.disabled = !isActive;
        pauseButton.textContent = isPaused
            ? getText("resume")
            : getText("pause");
    }

    if (stopButton) stopButton.disabled = !isActive;
}

function readLessonAloud() {
    if (!currentLesson) {
        alert(getText("noLesson"));
        return;
    }

    if (!window.speechSynthesis || !window.SpeechSynthesisUtterance) {
        alert(getText("readUnsupported"));
        return;
    }

    window.speechSynthesis.cancel();
    isReadingPaused = false;

    const utterance = new SpeechSynthesisUtterance(currentLesson);
    currentUtterance = utterance;

    utterance.lang = getSpeechLanguage();
    utterance.rate = Number(getSelectedLanguage("readingSpeed", "1"));

    const voiceSelect = getElement("readingVoice");

    if (voiceSelect && voiceSelect.value !== "") {
        const voices = window.speechSynthesis.getVoices();
        const selectedVoice = voices[Number(voiceSelect.value)];
        if (selectedVoice) utterance.voice = selectedVoice;
    }

    updateReadAloudButtons(true);
    showMessage(getElement("readingStatus"), getText("startReading"));

    utterance.onstart = () => {
        updateReadAloudButtons(true);
        showMessage(getElement("readingStatus"), getText("readingLesson"));
    };

    utterance.onend = () => {
        currentUtterance = null;
        isReadingPaused = false;
        updateReadAloudButtons(false);
        showMessage(getElement("readingStatus"), getText("readingCompleted"));
    };

    utterance.onerror = event => {
        currentUtterance = null;
        isReadingPaused = false;
        updateReadAloudButtons(false);

        if (event.error !== "canceled" && event.error !== "interrupted") {
            showMessage(getElement("readingStatus"), getText("readUnsupported"), true);
        }
    };

    window.speechSynthesis.speak(utterance);
}

function pauseOrResumeReading() {
    const speech = window.speechSynthesis;
    if (!speech || !currentUtterance) return;

    if (isReadingPaused || speech.paused) {
        speech.resume();
        isReadingPaused = false;
        updateReadAloudButtons(true, false);
        showMessage(getElement("readingStatus"), getText("readingResumed"));
    } else if (speech.speaking) {
        speech.pause();
        isReadingPaused = true;
        updateReadAloudButtons(true, true);
        showMessage(getElement("readingStatus"), getText("readingPaused"));
    }
}

function stopReading() {
    if (window.speechSynthesis) {
        window.speechSynthesis.cancel();
    }

    currentUtterance = null;
    isReadingPaused = false;
    updateReadAloudButtons(false);
    showMessage(getElement("readingStatus"), getText("readingStopped"));
}

function setupReadAloud() {
    getElement("readAloudButton")?.addEventListener("click", readLessonAloud);
    getElement("pauseReadingButton")?.addEventListener("click", pauseOrResumeReading);
    getElement("stopReadingButton")?.addEventListener("click", stopReading);

    updateReadAloudButtons(false);
    populateReadingVoices();

    if (window.speechSynthesis) {
        window.speechSynthesis.onvoiceschanged = populateReadingVoices;
    }
}


