async function checkQuizAnswer(answer) {
    if (isCheckingAnswer) return;

    if (!answer || !String(answer).trim()) {
        showMessage(getElement("feedback"), getText("chooseAnswer"), true);
        return;
    }

    isCheckingAnswer = true;

    const data = quizQuestions[currentQuestion];

    const expectedAnswer =
        data.correctAnswerText ||
        (typeof data.correctAnswer === "number"
            ? data.options[data.correctAnswer]
            : data.correctAnswer);

    const explanation = data.explanation || "";

    const buttons = getElement("quiz").querySelectorAll("button");
    buttons.forEach(button => button.disabled = true);

    try {
        const result = await sendRequest("/api/quiz/check", {
            question: data.question,
            expectedAnswer: String(expectedAnswer),
            learnerAnswer: String(answer),
            explanation,
            lessonLanguage: getSelectedLanguage(
                "lessonLanguage",
                getLanguageLocale(selectedInterfaceLanguage)
            )
        });

        const isCorrect = result.correct === true;
        if (isCorrect) score++;

        let feedback = result.feedback ||
            (isCorrect ? getText("excellent") : getText("goodTry"));

        if (result.correction) {
            feedback += " " + result.correction;
        }

        if (explanation && !result.explanation) {
            feedback += " " + getText("explanationLabel") + " " + explanation;
        }

        showMessage(getElement("feedback"), feedback, !isCorrect);

        const nextButton = document.createElement("button");
        nextButton.type = "button";
        nextButton.textContent =
            currentQuestion === quizQuestions.length - 1
                ? getText("results")
                : getText("next");

        nextButton.addEventListener("click", () => {
            currentQuestion++;
            renderQuestion();
        });

        getElement("quiz").appendChild(nextButton);

    } catch (error) {
        showMessage(
            getElement("feedback"),
            getText("answerError") + " " + error.message,
            true
        );

        buttons.forEach(button => button.disabled = false);

    } finally {
        isCheckingAnswer = false;
    }
}


