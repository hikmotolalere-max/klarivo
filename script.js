function startVoiceRecognition(target) {
    const SpeechRecognition =
        window.SpeechRecognition || window.webkitSpeechRecognition;

    if (!SpeechRecognition) {
        alert(getText("voiceUnsupported"));
        return;
    }

    if (speechRecognition) {
        speechRecognition.abort();
    }

    speechRecognition = new SpeechRecognition();
    speechRecognition.lang = getSelectedLanguage(
        "speakingLanguage",
        getLanguageLocale(selectedInterfaceLanguage)
    );
    speechRecognition.continuous = false;
    speechRecognition.interimResults = false;

    let statusElement;

    if (target === "topic") {
        statusElement = getElement("topicVoiceStatus");
    } else if (target === "top") {
        statusElement = getElement("topVoiceStatus");
    } else if (target === "quiz") {
        statusElement = getElement("quizVoiceStatus");
    } else {
        statusElement = getElement("voiceStatus");
    }

    showMessage(statusElement, getText("listening"));

    speechRecognition.onresult = event => {
        const transcript = event.results[0][0].transcript.trim();

        if (target === "topic") {
            getElement("topic").value = transcript;
            showMessage(statusElement, getText("topicAdded"));
        } else if (target === "quiz") {
            checkQuizAnswer(transcript);
            showMessage(statusElement, getText("answerReceived"));
        } else {
            getElement("askQuestion").value = transcript;
            showMessage(statusElement, getText("listeningAdded"));
        }
    };

    speechRecognition.onerror = event => {
        showMessage(statusElement, "Voice input error: " + event.error, true);
    };

    speechRecognition.onend = () => {
        speechRecognition = null;
    };

    try {
        speechRecognition.start();
    } catch (error) {
        showMessage(statusElement, getText("voiceUnsupported"), true);
    }
}


