async function startQuiz() {
    if (!currentLesson) {
        alert(getText("noLesson"));
        return;
    }

    const startButton = getElement("startQuizButton");
    const quizElement = getElement("quiz");

    const questionCount = Number(
        getSelectedLanguage("questionCount", "5")
    );

    startButton.disabled = true;
    startButton.textContent = getText("preparing");
    quizElement.textContent = getText("preparing");

    try {
        const result = await sendRequest("/api/quiz", {
            lesson: currentLesson,
            questionCount,
            lessonLanguage: getSelectedLanguage(
                "lessonLanguage",
                getLanguageLocale(selectedInterfaceLanguage)
            )
        });

        if (!Array.isArray(result.questions) || !result.questions.length) {
            throw new Error(getText("quizError"));
        }

        quizQuestions = result.questions;
        currentQuestion = 0;
        score = 0;

        getElement("quizArea").classList.remove("hidden");
        renderQuestion();

        quizElement.scrollIntoView({
            behavior: "smooth",
            block: "start"
        });

    } catch (error) {
        quizElement.textContent = getText("quizError") + " " + error.message;
        console.error("Quiz error:", error);

    } finally {
        startButton.disabled = false;
        startButton.textContent = getText("startQuiz");
    }
}


